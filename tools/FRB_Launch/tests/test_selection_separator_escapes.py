"""Selection separator escape handling should not touch contact values."""
import json
import unittest
from pathlib import Path

from core import decode_selection_separator, join_selection_values, Expander, load

ROOT = Path(__file__).resolve().parents[1]


class SelectionSeparatorEscapesTests(unittest.TestCase):
    def test_basic_escape_sequences(self):
        self.assertEqual(decode_selection_separator(r'\n'), '\n')
        self.assertEqual(decode_selection_separator(r'\r\n'), '\r\n')
        self.assertEqual(decode_selection_separator(r'\t'), '\t')
        self.assertEqual(decode_selection_separator(r'; \n'), '; \n')

    def test_plain_text_and_actual_newline_unchanged(self):
        for separator in ('; ', ', ', ' / ', '', '\n', '\r\n', '・'):
            with self.subTest(separator=repr(separator)):
                self.assertEqual(decode_selection_separator(separator), separator)

    def test_literal_backslash_and_unknown_sequences_remain_literal(self):
        self.assertEqual(decode_selection_separator(r'\\n'), r'\n')
        self.assertEqual(decode_selection_separator(r'\unknown'), r'\unknown')
        self.assertEqual(decode_selection_separator(r'\\\n'), '\\\n')
        self.assertEqual(decode_selection_separator(r'\x00'), r'\x00')

    def test_join_preserves_recipient_data_and_field_contract(self):
        choices = [
            {'value': 'alice@example.com', 'title': r'山田\nさん'},
            {'value': r'%APPDATA%\inside', 'title': 'B'},
        ]
        row = {'launch_selection_separator': r'\n'}
        self.assertEqual(join_selection_values(row, choices),
                         'alice@example.com\n%APPDATA%\\inside')
        row = {'launch_selection_separator': r'\t',
               'launch_selection_value_field': 'title'}
        self.assertEqual(join_selection_values(row, choices), r'山田\nさん' + '\tB')
        self.assertEqual(join_selection_values({}, choices),
                         'alice@example.com; %APPDATA%\\inside')

    def test_real_config_se_choice_separator(self):
        data = load(ROOT / 'config' / 'frb_launch_sample_data_v0_1.json')
        row = next(item for item in data['items'] if item['item_kind'] == 'selection'
                   and item.get('launch_selection_group_id') == 'se')
        choices = sorted((c for c in data['launch_choices']
                          if c.get('group_id') == 'se'), key=lambda c: c['sort_order'])[:2]
        self.assertEqual(row['launch_selection_separator'], r'; \n')
        value = join_selection_values(row, choices)
        self.assertEqual(value, choices[0]['value'] + '; \n' + choices[1]['value'])
        # SendKey/ClipboardCopy refer to the result variable. Expander must
        # preserve the actual newline generated by the selection join.
        result_key = row.get('launch_selection_result_name', 'recipients')
        command = row['launch_actions'][0]['launch_text']
        self.assertEqual(Expander(data, values={result_key: value}).expand(command), value)

    def test_escape_has_no_effect_on_value_without_separator(self):
        row = {'launch_selection_separator': r'\n'}
        self.assertEqual(join_selection_values(row, [{'value': r'hello\nworld'}]),
                         r'hello\nworld')


if __name__ == '__main__':
    unittest.main()
