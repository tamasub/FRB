// v0.17.1-rule-review-markdown-export-action
// ViewDef JSON -> Markdown export.
// Restores the global exportViewDefMarkdown() contract used by header and ActionRegistry.

function buildViewDefMarkdown() {
  if (!viewDef) throw new Error('Markdown出力するViewDefが読み込まれていません');
  const view = typeof mainView === 'function' ? mainView() : (viewDef?.views?.[0] ?? viewDef ?? {});
  const title = view?.caption ?? viewDef?.app?.name ?? 'ViewDef';
  const lines = [];

  lines.push(`# ${title}`);
  lines.push('');
  lines.push('<!-- Generated by FRB Studio / JSON Object Studio -->');
  lines.push('');
  if (typeof lastLoadedDefName !== 'undefined' && lastLoadedDefName) lines.push(`- ViewDef: \`${lastLoadedDefName}\``);
  lines.push(`- Exported At: ${(typeof studioFormatDateTime === 'function' ? studioFormatDateTime() : new Date().toLocaleString('sv-SE').replace(' ', '_'))}`);
  lines.push('');

  if (view?.layout || view?.toolbar || viewDef?.app) {
    lines.push('## 概要');
    lines.push('');
    lines.push('| 項目 | 値 |');
    lines.push('|---|---|');
    if (viewDef?.app?.name) lines.push(`| App | ${markdownEscapeTableCell(viewDef.app.name)} |`);
    if (viewDef?.app?.version) lines.push(`| Version | ${markdownEscapeTableCell(viewDef.app.version)} |`);
    if (view?.id) lines.push(`| View ID | ${markdownEscapeTableCell(view.id)} |`);
    if (view?.caption) lines.push(`| Caption | ${markdownEscapeTableCell(view.caption)} |`);
    const action = view?.toolbar?.executeButton?.action ?? viewDef?.toolbar?.executeButton?.action;
    if (action) lines.push(`| Execute Action | ${markdownEscapeTableCell(action)} |`);
    lines.push('');
  }

  const sections = Array.isArray(view?.sections) ? view.sections : [];
  lines.push('## Sections');
  lines.push('');
  lines.push('| ID | Caption | Type | DataPath | Fields |');
  lines.push('|---|---|---|---|---|');
  sections.forEach(section => {
    lines.push(`| ${markdownEscapeTableCell(section.id)} | ${markdownEscapeTableCell(section.caption)} | ${markdownEscapeTableCell(section.type)} | ${markdownEscapeTableCell(section.dataPath)} | ${(section.fields ?? []).length} |`);
  });
  lines.push('');

  sections.forEach(section => {
    lines.push(`## ${section.caption ?? section.id ?? 'Section'}`);
    lines.push('');
    lines.push(`- id: \`${section.id ?? ''}\``);
    lines.push(`- type: \`${section.type ?? ''}\``);
    lines.push(`- dataPath: \`${section.dataPath ?? ''}\``);
    lines.push('');
    const fields = Array.isArray(section.fields) ? section.fields : [];
    if (fields.length) {
      lines.push('| Field | Caption | Type | Grid | Edit | Search |');
      lines.push('|---|---|---|---|---|---|');
      fields.forEach(field => {
        const gridVisible = field.grid?.visible === false ? 'hidden' : 'visible';
        const editVisible = field.edit?.visible === false ? 'hidden' : (field.readonly || field.edit?.readonly ? 'readonly' : 'editable');
        const searchVisible = field.search?.visible === true ? 'visible' : '';
        lines.push(`| ${markdownEscapeTableCell(field.field)} | ${markdownEscapeTableCell(field.caption)} | ${markdownEscapeTableCell(field.type)} | ${gridVisible} | ${editVisible} | ${searchVisible} |`);
      });
      lines.push('');
    }
  });

  lines.push('## Raw ViewDef JSON');
  lines.push('');
  lines.push(markdownFence(JSON.stringify(viewDef, null, 2), 'json'));
  lines.push('');
  return lines.join('\n');
}

async function exportViewDefMarkdown() {
  const content = buildViewDefMarkdown();
  const rawName = (typeof lastLoadedDefName !== 'undefined' && lastLoadedDefName) ? lastLoadedDefName : 'view_def.json';
  const base = markdownSafeSlug(markdownBaseNameWithoutExt(rawName), 'viewdef_export');
  const name = `00_Common/${base}_viewdef_${markdownNowStamp()}.md`;
  const result = await markdownSaveManagedFile(name, content, rawName);
  const saved = result.saved || name;
  if (typeof setStatus === 'function') setStatus(`ViewDef Markdown出力しました: ${saved}`);
  if (!result.downloaded) markdownOpenViewer(saved);
  return result;
}
